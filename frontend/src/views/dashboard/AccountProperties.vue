<template>
  <div class="page-container">
    <div class="page-header">
      <h2 class="page-title"><el-icon><Setting /></el-icon> {{ t('dashboard.accountProperties') }}</h2>
      <div class="header-actions">
        <el-button size="small" @click="refreshData"><el-icon><Refresh /></el-icon> {{ t('common.refresh') }}</el-button>
      </div>
    </div>
    <el-card shadow="hover" v-loading="loading">
      <el-table :data="items" stripe style="width:100%" :empty-text="t('common.noData')">
        <el-table-column prop="property" :label="t('common.property')" min-width="160" />
        <el-table-column prop="value" :label="t('common.value')" min-width="200" show-overflow-tooltip />
        <el-table-column prop="setterRS" :label="t('common.setter')" width="200" show-overflow-tooltip />
        <el-table-column prop="recipientRS" :label="t('common.recipient')" width="200" show-overflow-tooltip />
      </el-table>
      <div class="pagination-container" v-if="total > 20">
        <el-pagination v-model:current-page="page" :page-size="20" :total="total" layout="prev,pager,next" @current-change="refreshData" />
      </div>
    </el-card>
  </div>
</template>

<script setup lang="ts">
import { ref, onMounted } from 'vue'
import { useI18n } from 'vue-i18n'
import { ElMessage } from 'element-plus'
import { nrcsApi } from '@/api/modules/nrcs.api'

const { t } = useI18n()
const loading = ref(false)
const items = ref<any[]>([])
const total = ref(0)
const page = ref(1)

onMounted(() => refreshData())

async function refreshData() {
  loading.value = true
  try {
    const accountId = localStorage.getItem('nrcs_account_id') || ''
    const result = await nrcsApi.getAccountProperties(accountId)
    items.value = (result as any).properties || []
    total.value = items.value.length
  } catch (e: any) { ElMessage.error(e?.message || t('common.loadError')) }
  finally { loading.value = false }
}
</script>
